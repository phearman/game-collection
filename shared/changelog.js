// 不指定遊戲時顯示全部;篩選保留原本的日期與項目順序。
export function filterChangelog(entries, code) {
  if (!code) return entries;
  return entries
    .map((entry) => ({
      ...entry,
      items: entry.items.filter((item) => item.scope === code || item.scope === '全站'),
    }))
    .filter((entry) => entry.items.length > 0);
}
